'use strict';
// Full build: Plasma 6 package (compiled .qsb), Plasma 5 package (GLSL sources),
// RPM source archives for MOS 12 / MOS 13 and the Windows (Lively) theme.
const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const {createHash} = require('node:crypto');
const scene = require('../src/scene.js');
const root = path.resolve(__dirname, '..');
const id = 'org.ny.livewallpaper';
const version = require('../package.json').version;
const staging = path.join(root, '.cache/release');

function write(file, content) {
  fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, content);
}
function findQsb() {
  if (process.env.QSB) return process.env.QSB;
  const python = spawnSync('python', ['-c', 'import pathlib, PySide6; print(pathlib.Path(PySide6.__file__).parent / "qsb.exe")'], {encoding: 'utf8'});
  const candidate = python.stdout?.trim();
  if (candidate && fs.existsSync(candidate)) return candidate;
  for (const name of ['qsb', 'qsb6', '/usr/lib/qt6/bin/qsb', '/usr/lib64/qt6/bin/qsb']) {
    if (spawnSync(name, ['--version'], {encoding: 'utf8', timeout: 5000}).status === 0) return name;
  }
  throw new Error('Qt 6 qsb not found. Set QSB to the Qt Shader Tools executable (build machine only).');
}
// Qt multiplies the item opacity in; WebGL draws opaque.
const body = scene.body.replace('FRAG = vec4(clamp(outColor, 0., 1.), 1.);',
  'FRAG = vec4(clamp(outColor, 0., 1.), 1.) * qt_Opacity;');
if (body === scene.body) throw new Error('Shader output statement not found');

function qt6Shader() {
  return `#version 440
layout(location=0) in vec2 qt_TexCoord0;
layout(location=0) out vec4 fragColor;
layout(std140, binding=0) uniform buf {
  mat4 qt_Matrix;
  float qt_Opacity;
${scene.uniforms.map(([type, name]) => `  ${type} ${name};`).join('\n')}
};
${scene.samplers.map((name, i) => `layout(binding=${i + 1}) uniform sampler2D ${name};`).join('\n')}
#define vUV qt_TexCoord0
#define TEX texture
#define FRAG fragColor
${body}
`;
}
function qt5Shader() {
  return `#ifdef GL_ES
precision highp float;
#endif
varying highp vec2 qt_TexCoord0;
uniform lowp float qt_Opacity;
${scene.uniforms.map(([type, name]) => `uniform ${type} ${name};`).join('\n')}
${scene.samplers.map(name => `uniform sampler2D ${name};`).join('\n')}
#define vUV qt_TexCoord0
#define TEX texture2D
#define FRAG gl_FragColor
${body}
`;
}
// The time-of-day logic is shared with QML: the same functions, as source.
function sceneConfig() {
  const functions = ['smoothstep', 'hash1', 'noise1', 'sunElevation', 'sceneState'].map(name => {
    const source = scene.sources[name];
    if (!source) throw new Error('Missing shared function ' + name);
    return source;
  });
  return `.pragma library\n// Generated by build/build.cjs from src/scene.js. Do not edit.\n` +
    `var defaults = ${JSON.stringify(scene.defaults)};\nvar ranges = ${JSON.stringify(scene.ranges)};\n` +
    `var pixelLimits = ${JSON.stringify(scene.pixelLimits)};\n${functions.join('\n')}\n`;
}
function sceneQml(source) {
  const marker = /^\s*\/\/ @SCENE_UNIFORMS@.*$/m;
  if (!marker.test(source)) throw new Error('Scene.qml uniform marker not found');
  const lines = scene.uniforms.filter(([, name]) => !['uCover', 'uOffset', 'uResolution'].includes(name))
    .map(([type, name]) => {
      if (type !== 'float') throw new Error('Unexpected uniform type ' + type);
      return `            property real ${name}: scene.values.${name}`;
    });
  return source.replace(marker, lines.join('\n'));
}
function assets() {
  const text = fs.readFileSync(path.join(root, 'src/assets/scene-assets.js'), 'utf8');
  const match = text.match(/window\.NY_ASSETS=(\{.*\});/);
  if (!match) throw new Error('Run npm run assets first.');
  return JSON.parse(match[1]);
}
const images = {plate: 'plate.jpg', day: 'day.jpg', masks: 'masks.png', masks2: 'masks2.png',
  glow: 'glow.png', off: 'off.jpg', shade: 'shade.png', glyphs: 'glyphs.png'};

function main() {
  const revision = sceneRevision();
  const qsb = findQsb();
  fs.rmSync(staging, {recursive: true, force: true});
  const destination = path.join(staging, 'native', id);
  fs.cpSync(path.join(root, 'plasma'), destination, {recursive: true});
  const contents = path.join(destination, 'contents');
  const scenePath = path.join(contents, 'ui/Scene.qml');
  fs.writeFileSync(scenePath, sceneQml(fs.readFileSync(scenePath, 'utf8')));
  write(path.join(contents, 'ui/SceneConfig.js'), sceneConfig());
  const entries = Object.entries(scene.defaults).filter(([name]) => name !== 'time').map(([name, value]) =>
    `    <entry name="${name}" type="${typeof value === 'string' ? 'String' : 'Double'}"><default>${value}</default></entry>`);
  write(path.join(contents, 'config/main.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<kcfg xmlns="http://www.kde.org/standards/kcfg/1.0"><kcfgfile name=""/><group name="General">\n${entries.join('\n')}\n    <entry name="paused" type="Bool"><default>false</default></entry>\n    <entry name="autoPause" type="Bool"><default>true</default></entry>\n</group></kcfg>\n`);
  const data = assets();
  for (const [key, file] of Object.entries(images)) {
    write(path.join(contents, 'images', file), Buffer.from(data[key].split(',')[1], 'base64'));
  }
  // GLSL sources stay in the cache; the Plasma 6 package ships compiled .qsb only.
  const source = path.join(staging, 'shaders/scene.frag');
  write(source, qt6Shader());
  const target = path.join(contents, 'shaders/scene.frag.qsb');
  fs.mkdirSync(path.dirname(target), {recursive: true});
  const result = spawnSync(qsb, ['--qsbversion', '64', '--glsl', '100 es,120,150', '--hlsl', '50', '--msl', '12', '-o', target, source], {encoding: 'utf8', timeout: 60000});
  if (result.status !== 0) throw new Error(`qsb: ${result.stderr || result.error}`);
  write(path.join(staging, 'scene-revision.json'), JSON.stringify({revision}, null, 2));

  const plasma5 = path.join(staging, 'mos12', id);
  require('./plasma5.cjs').preparePlasma5(destination, plasma5, qt5Shader());
  for (const target of ['mos12', 'mos13']) {
    const sourceName = `ny-wallpaper-${version}`;
    const sourceParent = path.join(staging, 'sources', target);
    const sourceDirectory = path.join(sourceParent, sourceName);
    fs.mkdirSync(sourceDirectory, {recursive: true});
    fs.cpSync(target === 'mos12' ? plasma5 : destination, path.join(sourceDirectory, id), {recursive: true});
    fs.copyFileSync(path.join(root, `docs/${target}.md`), path.join(sourceDirectory, `README.${target}.md`));
    fs.copyFileSync(path.join(root, 'docs/settings.png'), path.join(sourceDirectory, 'settings.png'));
    fs.copyFileSync(path.join(root, 'LICENSE'), path.join(sourceDirectory, 'LICENSE'));
    const sourceArchive = path.join(root, `.cache/rpm/${target}/SOURCES`, sourceName + '.tar.gz');
    fs.mkdirSync(path.dirname(sourceArchive), {recursive: true});
    // Relative paths: GNU tar would read "D:" in a Windows path as a remote host.
    const tar = spawnSync('tar', ['-czf', path.relative(sourceParent, sourceArchive).split(path.sep).join('/'), sourceName],
      {cwd: sourceParent, encoding: 'utf8', timeout: 60000});
    if (tar.status !== 0) throw new Error(`Source archive: ${tar.stderr || tar.error}`);
  }
  fs.rmSync(path.join(root, 'dist'), {recursive: true, force: true});
  require('./lively.cjs').main();
  console.log('Native packages and RPM source archives prepared under .cache/');
}
function sceneRevision() {
  const hash = createHash('sha256');
  for (const file of ['src/scene.js', 'src/assets/scene-assets.js']) hash.update(fs.readFileSync(path.join(root, file)));
  return hash.digest('hex');
}
if (require.main === module) {
  try { main(); } catch (error) { console.error(error); process.exitCode = 1; }
}
module.exports = {qt6Shader, qt5Shader, sceneConfig, sceneQml, sceneRevision, id};
